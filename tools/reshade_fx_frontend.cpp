// ReShade FX syntax/type checking and HLSL generation, without FXC/DXC or a GPU.
// Build against the unmodified official ReShade 6.7.3 effect front-end sources.
#include "effect_codegen.hpp"
#include "effect_parser.hpp"
#include "effect_preprocessor.hpp"
#include <filesystem>
#include <iostream>
#include <memory>
#include <string>

int main(int argc, char **argv)
{
    if (argc < 3)
    {
        std::cerr << "usage: reshade-fx-frontend effect.fx framework-include-directory [NAME=VALUE ...]\n";
        return 2;
    }
    reshadefx::preprocessor pp;
    pp.add_include_path(std::filesystem::path(argv[1]).parent_path());
    pp.add_include_path(argv[2]);
    for (int i = 3; i < argc; ++i)
    {
        const std::string definition(argv[i]);
        const auto separator = definition.find('=');
        if (separator == std::string::npos) return 2;
        const auto name = definition.substr(0, separator);
        pp.add_macro_definition(name, definition.substr(separator + 1));
    }
    pp.add_macro_definition("__RESHADE__", "60703");
    pp.add_macro_definition("__RESHADE_FXC__", "1");
    pp.add_macro_definition("__RESHADE_PERFORMANCE_MODE__", "0");
    pp.add_macro_definition("__RENDERER__", "0xb000");
    pp.add_macro_definition("BUFFER_WIDTH", "2560");
    pp.add_macro_definition("BUFFER_HEIGHT", "1440");
    pp.add_macro_definition("BUFFER_RCP_WIDTH", "(1.0 / BUFFER_WIDTH)");
    pp.add_macro_definition("BUFFER_RCP_HEIGHT", "(1.0 / BUFFER_HEIGHT)");
    if (!pp.append_file(argv[1]))
    {
        std::cerr << pp.errors();
        return 1;
    }
    std::unique_ptr<reshadefx::codegen> backend(reshadefx::create_codegen_hlsl(50, true, false));
    reshadefx::parser parser;
    const bool parsed = parser.parse(pp.output(), backend.get());
    std::cerr << pp.errors() << parser.errors();
    if (!parsed) return 1;
    const auto generated = backend->finalize_code();
    if (generated.empty()) return 1;
    std::cout << "PASS: ReShade 6.7.3 FX frontend and SM5 HLSL generation; "
              << generated.size() << " generated bytes. No DXBC/DXIL compilation or GPU execution.\n";
}
